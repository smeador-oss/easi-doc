export function initPortalSwitcher(navEl, portals, currentPortalId, { isAdmin = false } = {}) {
  if (!navEl) return;

  const addBtn = isAdmin
    ? `<button class="portal-add-btn" id="header-new-portal-btn" title="New Portal">+</button>`
    : '';

  // Always show portal tabs (even for a single portal — shows the icon in the header)
  if (!portals || portals.length === 0) {
    navEl.innerHTML = addBtn;
    return;
  }

  const tabs = portals.map(p => {
    const isActive = p.id === currentPortalId;
    const iconSvg = ICONS[p.icon] || ICONS.file;
    return `<a class="portal-link${isActive ? ' portal-link-active' : ''}"
               href="#/${escapeAttr(p.id)}/"
               title="${escapeAttr(p.title)}">
      <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">${iconSvg}</svg>
      <span>${escapeHtml(p.title)}</span>
    </a>`;
  }).join('');

  navEl.innerHTML = tabs + addBtn;
}

function escapeHtml(str) {
  const div = document.createElement('div');
  div.textContent = str || '';
  return div.innerHTML;
}

function escapeAttr(str) {
  return (str || '').replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}
